export const DICTIONARIES: Record<Locale, Dictionary> = {
  en: EN,
  zh: ZH,
  'zh-Hant': ZH_HANT,
};

/** 支持 `{name}` 形式的简单插值（如 `第 {page} / {total} 页`）。 */
export function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, key) =>
    Object.prototype.hasOwnProperty.call(vars, key) ? String(vars[key]) : `{${key}}`,
  );
}

export interface Translator {
  (key: string, vars?: Record<string, string | number>): string;
}

/**
 * 生成翻译函数。宿主可传入 `overrides` 覆盖任意键（含新增语言）。
 * 查找优先级：overrides → 目标语言 → 英文 → key 本身。
 */
export function createTranslator(locale: Locale = DEFAULT_LOCALE, overrides?: Partial<Dictionary>): Translator {
  const base = DICTIONARIES[locale] ?? EN;
  return function t(key: string, vars?: Record<string, string | number>): string {
    const value = overrides?.[key] ?? base[key] ?? EN[key] ?? key;
    return interpolate(value, vars);
  };
}

export function isLocale(value: string): value is Locale {
  return (LOCALES as string[]).includes(value);
}